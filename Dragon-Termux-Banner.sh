#!/data/data/com.termux/files/usr/bin/bash
# ============================================================
# DRAGON BANNER MAKER PRO - Termux
# Creates a colourful cowsay dragon startup banner.
# ============================================================

set -o pipefail

APP_DIR="$HOME/.config/dragon-banner-maker"
SETTINGS="$APP_DIR/settings"
STARTUP="$APP_DIR/startup.sh"
BASHRC="$HOME/.bashrc"
BEGIN_MARK="# >>> DRAGON BANNER MAKER >>>"
END_MARK="# <<< DRAGON BANNER MAKER <<<"

RED='\033[1;31m'
GREEN='\033[1;32m'
CYAN='\033[1;36m'
YELLOW='\033[1;33m'
MAGENTA='\033[1;35m'
WHITE='\033[1;37m'
RESET='\033[0m'

pause() {
    echo
    read -rp "Press Enter to continue..." _
}

header() {
    clear
    printf "${CYAN}"
    printf '%s\n' '╔══════════════════════════════════════════════╗'
    printf '%s\n' '║          DRAGON BANNER MAKER PRO             ║'
    printf '%s\n' '║       Rainbow ASCII Startup Builder          ║'
    printf '%s\n' '╚══════════════════════════════════════════════╝'
    printf "${RESET}\n"
}

have_cowsay() { command -v cowsay >/dev/null 2>&1; }
have_lolcat() { command -v lolcat >/dev/null 2>&1; }

install_dependencies() {
    echo -e "${YELLOW}Checking required packages...${RESET}"
    if ! have_cowsay; then
        pkg install cowsay -y || {
            echo -e "${RED}Could not install cowsay. Check your internet/repository.${RESET}"
            return 1
        }
    fi
    if ! have_lolcat; then
        pkg install ruby -y || return 1
        gem install lolcat || {
            echo -e "${YELLOW}lolcat installation failed. Banner will use normal colors.${RESET}"
        }
    fi
    return 0
}

load_settings() {
    [[ -f "$SETTINGS" ]] && source "$SETTINGS"
    USER_NAME="${USER_NAME:-H4CK3R}"
    LABEL="${LABEL:-T-mux-Banner}"
    TAGLINE="${TAGLINE:-LEARN TODAY - SECURE TOMORROW}"
    ART_NAME="${ART_NAME:-dragon}"
    COLOR_MODE="${COLOR_MODE:-rainbow}"
    PROMPT_STYLE="${PROMPT_STYLE:-classic}"
    SHOW_TAGLINE="${SHOW_TAGLINE:-yes}"
    SHOW_INFO="${SHOW_INFO:-yes}"
}

save_settings() {
    mkdir -p "$APP_DIR"
    {
        printf 'USER_NAME=%q\n' "$USER_NAME"
        printf 'LABEL=%q\n' "$LABEL"
        printf 'TAGLINE=%q\n' "$TAGLINE"
        printf 'ART_NAME=%q\n' "$ART_NAME"
        printf 'COLOR_MODE=%q\n' "$COLOR_MODE"
        printf 'PROMPT_STYLE=%q\n' "$PROMPT_STYLE"
        printf 'SHOW_TAGLINE=%q\n' "$SHOW_TAGLINE"
        printf 'SHOW_INFO=%q\n' "$SHOW_INFO"
    } > "$SETTINGS"
    chmod 600 "$SETTINGS"
}

render_art() {
    local art="$1"
    if have_cowsay; then
        cowsay -f "$art" "Cow Say and Lol Cat (dragon)" 2>/dev/null
    else
        cat <<'DRAGON'
             \                    / \  //\
              \    |\___/|        /   \//  \\
               \   /0  0  \__    /    //  | \ \
                   /     /  \/_/    //   |  \  \
                   @_^_@'/   \/_   //    |   \   \
                   //_^_/     \/_ //     |    \    \
                ( //) |        \///      |     \     \
              ( / /) _|_ /   )  //       |      \     /
            ( // /) '/,_ _ _/  ( ; -.    |       \   /
          (( / / )) ,-{        _      `-.|        |  /
         (( // / ))  '/\      /                 /
          (( / / ))     `.   {            }     /
           (( // ))       /  \           /    /
            (( / ))      /    \        /     /
             (( ))      /      \______/     /
              ||       /                  /
              ||      /__________________/
             /__\
DRAGON
    fi
}

paint() {
    case "$COLOR_MODE" in
        rainbow)
            if have_lolcat; then lolcat -f; else cat; fi
            ;;
        red)     sed $'s/^/\x1b[1;31m/;s/$/\x1b[0m/' ;;
        green)   sed $'s/^/\x1b[1;32m/;s/$/\x1b[0m/' ;;
        cyan)    sed $'s/^/\x1b[1;36m/;s/$/\x1b[0m/' ;;
        magenta) sed $'s/^/\x1b[1;35m/;s/$/\x1b[0m/' ;;
        yellow)  sed $'s/^/\x1b[1;33m/;s/$/\x1b[0m/' ;;
        *) cat ;;
    esac
}

show_banner() {
    load_settings
    printf '\n'
    if have_cowsay; then
        cowsay -f "$ART_NAME" "Cow Say and Lol Cat (dragon)" 2>/dev/null | paint
    else
        render_art "$ART_NAME" | paint
    fi
    printf '\n'
    printf '%s\n' "$USER_NAME [$LABEL]" | paint
    if [[ "$SHOW_TAGLINE" == "yes" ]]; then
        printf '%s\n' "$TAGLINE" | paint
    fi
    if [[ "$SHOW_INFO" == "yes" ]]; then
        printf '\n'
        printf 'SYSTEM : ONLINE\n' | paint
        printf 'SHELL  : BASH\n' | paint
        printf 'DEVICE : ANDROID / TERMUX\n' | paint
    fi
    printf '\n'
}

make_startup_file() {
    cat > "$STARTUP" <<'STARTUP_EOF'
# Generated by Dragon Banner Maker Pro
[[ $- == *i* ]] || return 0
[[ -n "${DRAGON_BANNER_SHOWN:-}" ]] && return 0
export DRAGON_BANNER_SHOWN=1

DBM_DIR="$HOME/.config/dragon-banner-maker"
[[ -f "$DBM_DIR/settings" ]] && source "$DBM_DIR/settings"

dbm_lolcat() {
    if command -v lolcat >/dev/null 2>&1; then lolcat -f; else cat; fi
}

dbm_paint() {
    case "${COLOR_MODE:-rainbow}" in
        rainbow) dbm_lolcat ;;
        red)     sed $'s/^/\x1b[1;31m/;s/$/\x1b[0m/' ;;
        green)   sed $'s/^/\x1b[1;32m/;s/$/\x1b[0m/' ;;
        cyan)    sed $'s/^/\x1b[1;36m/;s/$/\x1b[0m/' ;;
        magenta) sed $'s/^/\x1b[1;35m/;s/$/\x1b[0m/' ;;
        yellow)  sed $'s/^/\x1b[1;33m/;s/$/\x1b[0m/' ;;
        *) cat ;;
    esac
}

if command -v cowsay >/dev/null 2>&1; then
    cowsay -f "${ART_NAME:-dragon}" " " 2>/dev/null | dbm_paint
else
    printf 'Install cowsay to display the selected ASCII art.\n'
fi

printf '\n'
printf '%s [%s]\n' "${USER_NAME:-H4CK3R}" "${LABEL:-T-mux-Banner}" | dbm_paint
if [[ "${SHOW_TAGLINE:-yes}" == "yes" ]]; then
    printf '%s\n' "${TAGLINE:-LEARN TODAY - SECURE TOMORROW}" | dbm_paint
fi
if [[ "${SHOW_INFO:-yes}" == "yes" ]]; then
    printf '\nSYSTEM : ONLINE\nSHELL  : BASH\nDEVICE : ANDROID / TERMUX\n' | dbm_paint
fi
printf '\n'

case "${PROMPT_STYLE:-classic}" in
    classic)
        PS1='\[\033[1;33m\]'"${USER_NAME:-H4CK3R}"'\[\033[1;34m\][\[\033[1;36m\]'"${LABEL:-T-mux-Banner}"'\[\033[1;34m\]]\[\033[1;31m\]:# \[\033[0m\]'
        ;;
    arrow)
        PS1='\[\033[1;32m\]┌─[\[\033[1;36m\]'"${USER_NAME:-H4CK3R}"'\[\033[1;32m\]]─[\[\033[1;35m\]'"${LABEL:-T-mux-Banner}"'\[\033[1;32m\]]\n└──╼ \[\033[1;33m\]$\[\033[0m\] '
        ;;
    minimal)
        PS1='\[\033[1;36m\]'"${USER_NAME:-H4CK3R}"'\[\033[0m\] ❯ '
        ;;
esac
STARTUP_EOF
    chmod 600 "$STARTUP"
}

install_hook() {
    touch "$BASHRC"
    if ! grep -Fq "$BEGIN_MARK" "$BASHRC"; then
        {
            printf '\n%s\n' "$BEGIN_MARK"
            printf '[ -f "$HOME/.config/dragon-banner-maker/startup.sh" ] && source "$HOME/.config/dragon-banner-maker/startup.sh"\n'
            printf '%s\n' "$END_MARK"
        } >> "$BASHRC"
    fi
}

remove_hook() {
    if [[ -f "$BASHRC" ]]; then
        local tmp
        tmp="$(mktemp)"
        awk -v start="$BEGIN_MARK" -v end="$END_MARK" '
            $0 == start {skip=1; next}
            $0 == end {skip=0; next}
            !skip {print}
        ' "$BASHRC" > "$tmp"
        cat "$tmp" > "$BASHRC"
        rm -f "$tmp"
    fi
}

choose_art() {
    echo
    echo "Available cowsay art:"
    echo "1) dragon (recommended - screenshot style)"
    echo "2) tux"
    echo "3) stegosaurus"
    echo "4) vader"
    echo "5) ghostbusters"
    echo "6) random available cow"
    read -rp "Choose art [1-6]: " a
    case "$a" in
        2) ART_NAME="tux" ;;
        3) ART_NAME="stegosaurus" ;;
        4) ART_NAME="vader" ;;
        5) ART_NAME="ghostbusters" ;;
        6)
            local list
            list="$(cowsay -l 2>/dev/null | tr ' ' '\n' | grep -vE '^(Cow files|are|available|in|the|following|directories:|)$' | shuf -n 1)"
            ART_NAME="${list:-dragon}"
            ;;
        *) ART_NAME="dragon" ;;
    esac
    if ! cowsay -f "$ART_NAME" " " >/dev/null 2>&1; then
        ART_NAME="dragon"
    fi
}

create_or_update() {
    install_dependencies || return
    mkdir -p "$APP_DIR"
    load_settings

    echo
    read -rp "Banner username [${USER_NAME}]: " v
    [[ -n "$v" ]] && USER_NAME="$v"

    read -rp "Banner label [${LABEL}]: " v
    [[ -n "$v" ]] && LABEL="$v"

    read -rp "Tagline [${TAGLINE}]: " v
    [[ -n "$v" ]] && TAGLINE="$v"

    choose_art

    echo
    echo "Color mode:"
    echo "1) Rainbow (lolcat)"
    echo "2) Red   3) Green   4) Cyan"
    echo "5) Magenta   6) Yellow"
    read -rp "Choose color [1-6]: " c
    case "$c" in
        2) COLOR_MODE="red" ;;
        3) COLOR_MODE="green" ;;
        4) COLOR_MODE="cyan" ;;
        5) COLOR_MODE="magenta" ;;
        6) COLOR_MODE="yellow" ;;
        *) COLOR_MODE="rainbow" ;;
    esac

    echo
    echo "Prompt style:"
    echo "1) H4CK3R[Label]:#"
    echo "2) Two-line arrow prompt"
    echo "3) Minimal prompt"
    read -rp "Choose prompt [1-3]: " p
    case "$p" in
        2) PROMPT_STYLE="arrow" ;;
        3) PROMPT_STYLE="minimal" ;;
        *) PROMPT_STYLE="classic" ;;
    esac

    echo
    read -rp "Show tagline? [Y/n]: " v
    [[ "$v" =~ ^[Nn]$ ]] && SHOW_TAGLINE="no" || SHOW_TAGLINE="yes"

    read -rp "Show system information? [Y/n]: " v
    [[ "$v" =~ ^[Nn]$ ]] && SHOW_INFO="no" || SHOW_INFO="yes"

    save_settings
    make_startup_file
    install_hook

    echo
    echo -e "${GREEN}Banner installed/updated successfully!${RESET}"
    echo "Open a new Termux session to see it."
    pause
}

preview_banner() {
    if [[ ! -f "$SETTINGS" ]]; then
        echo -e "${YELLOW}No banner setup found. Create one first.${RESET}"
        pause
        return
    fi
    show_banner
    pause
}

uninstall_banner() {
    echo
    read -rp "Remove startup banner and prompt? [y/N]: " answer
    [[ "$answer" =~ ^[Yy]$ ]] || return
    remove_hook
    rm -rf "$APP_DIR"
    unset DRAGON_BANNER_SHOWN
    echo -e "${GREEN}Dragon Banner Maker removed from .bashrc.${RESET}"
    echo "Other .bashrc content has been kept."
    pause
}

main_menu() {
    while true; do
        header
        echo "1) Create / Update banner"
        echo "2) Preview current banner"
        echo "3) List available cowsay art"
        echo "4) Uninstall banner"
        echo "5) Exit"
        echo
        read -rp "Select option: " choice
        case "$choice" in
            1) create_or_update ;;
            2) preview_banner ;;
            3)
                install_dependencies
                echo
                cowsay -l 2>/dev/null
                pause
                ;;
            4) uninstall_banner ;;
            5) exit 0 ;;
            *) echo -e "${RED}Invalid option.${RESET}"; sleep 1 ;;
        esac
    done
}

main_menu
